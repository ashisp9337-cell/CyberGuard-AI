"""(10 Nov) The Deepfake module reads every file's own metadata - pictures, videos, recordings - from the file's
CONTENT, so a renamed file (a .jpg called .png, a video called .jpg, no name ending at all) is read the same way.
A file without metadata (shared through WhatsApp / a share link, a screenshot) is simply checked on its pixels / sound.
All test files are made here; no real person's picture is used."""
import os
