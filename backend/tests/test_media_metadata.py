XMP_AI = (b'<x:xmpmeta xmlns:x="adobe:ns:meta/"><rdf:RDF xmlns:rdf="http://www.w3.org/1999/02/22-rdf-syntax-ns#">'
          b'<rdf:Description xmlns:Iptc4xmpExt="http://iptc.org/std/Iptc4xmpExt/2008-02-29/" '
          b'Iptc4xmpExt:DigitalSourceType="http://cv.iptc.org/newscodes/digitalsourcetype/trainedAlgorithmicMedia"/>'
          b'</rdf:RDF></x:xmpmeta>')


def _img():
    rng = np.random.default_rng(1)
    return Image.fromarray(rng.normal(128, 30, (128, 160, 3)).clip(0, 255).astype(np.uint8))


def _exif(software=None, make=None, model=None):
    e = Image.Exif()
    if software:
        e[0x0131] = software
    if make:
        e[0x010F] = make
    if model:
        e[0x0110] = model
    return e


def _heif_ok():
    try:
        import pillow_heif
        pillow_heif.register_heif_opener()
        return True
    except ImportError:
        return False


@pytest.mark.parametrize("name,fmt,kwargs", [
    ("a.jpg", "JPEG", {"exif": _exif("Midjourney v6")}),
    ("b.jpg", "JPEG", {"xmp": XMP_AI}),
    ("c.webp", "WEBP", {"xmp": XMP_AI}),
    ("d.tif", "TIFF", {"tiffinfo": {305: "Stable Diffusion XL"}}),
    ("e.gif", "GIF", {"comment": b"Made with Midjourney"}),
    ("renamed_jpeg.png", "JPEG", {"exif": _exif("DALL-E 3")}),          # a JPEG with a .png name
    ("no_name_ending", "JPEG", {"exif": _exif("Adobe Firefly")}),       # saved without .jpg
])
def test_ai_metadata_is_found_in_every_picture_format_and_name(tmp_path, name, fmt, kwargs):
    p = tmp_path / name
    _img().save(p, fmt, **kwargs)
    assert R.file_kind(str(p), name) == "image"
    prov = AI.provenance(str(p))
    assert prov["proof"], prov
    assert AI.metadata_summary(str(p)).startswith(f"Format {fmt}")


@pytest.mark.skipif(not _heif_ok(), reason="pillow-heif not installed")
@pytest.mark.parametrize("ext", ["heic", "avif"])
def test_iphone_heic_and_avif_metadata(tmp_path, ext):
    p = tmp_path / f"photo.{ext}"
    _img().save(p, exif=_exif("DALL-E 3"))
    assert R.file_kind(str(p), p.name) == "image" and AI.provenance(str(p))["proof"]


def test_camera_photo_and_stripped_photo_are_described_not_judged(tmp_path):
    cam, bare = tmp_path / "cam.jpg", tmp_path / "shared.jpg"
    _img().save(cam, exif=_exif("G998BXXU5", "samsung", "SM-G998B"))
    _img().save(bare)
    assert not AI.provenance(str(cam))["proof"] and not AI.provenance(str(bare))["proof"]
    assert "camera / phone: samsung SM-G998B" in AI.metadata_summary(str(cam))
    s = AI.metadata_summary(str(bare))
    assert "no metadata" in s and "proves nothing" in s


av = pytest.importorskip("av")


def _video(path, fmt=None, **meta):
    with av.open(str(path), "w", format=fmt) as c:
        for k, v in meta.items():
            c.metadata[k] = v
        s = c.add_stream("mpeg4", rate=10)
        s.width, s.height, s.pix_fmt = 64, 48, "yuv420p"
        for i in range(5):
            fr = av.VideoFrame.from_ndarray(np.full((48, 64, 3), i * 40, np.uint8), format="rgb24")
            for pk in s.encode(fr):
                c.mux(pk)
        for pk in s.encode():
            c.mux(pk)


def test_video_metadata_is_read_even_when_renamed(tmp_path):
    good = tmp_path / "clip.mp4"
    _video(good, comment="Generated by Google Veo 3")
    renamed = tmp_path / "clip_renamed.jpg"
    shutil.copy(good, renamed)
    assert R.file_kind(str(renamed), renamed.name) == "video"
    for p in (good, renamed):
        prov = VP.provenance(str(p))
        assert prov["proof"] and "Google Veo" in prov["findings"][0]["detail"]
        assert "comment: Generated by Google Veo 3" in VP.metadata_summary(str(p))


def test_renamed_video_goes_to_the_video_checks(tmp_path, monkeypatch):
    """A video called .jpg was sent to the PICTURE checks before (10 Nov fix)."""
    from app.detectors import deepfake
    seen = []
    monkeypatch.setattr(deepfake, "_video_result", lambda fp, title: seen.append(fp) or {"riskScore": 1})
    p = tmp_path / "x.jpg"
    _video(p, fmt="mp4")
    assert deepfake.analyze_media(str(p), "x.jpg")["riskScore"] == 1 and seen == [str(p)]


def test_video_without_metadata_is_described(tmp_path):
    p = tmp_path / "plain.mp4"
    _video(p)
    assert not VP.provenance(str(p))["proof"]
    assert VP.metadata_summary(str(p)).startswith("Container MP4 / MOV")


def test_recording_metadata_naming_an_ai_voice_tool(tmp_path):
    from app.detectors import voice_audio
    p = tmp_path / "voice_note"                       # no name ending
    with av.open(str(p), "w", format="wav") as c:
        c.metadata["comment"] = "Created with ElevenLabs"
        s = c.add_stream("pcm_s16le", rate=16000)
        fr = av.AudioFrame.from_ndarray(np.zeros((1, 16000), np.int16), format="s16", layout="mono")
        fr.sample_rate = 16000
        for pk in s.encode(fr):
            c.mux(pk)
        for pk in s.encode():
            c.mux(pk)
    assert R.file_kind(str(p), p.name) == "audio"
    facts = voice_audio.file_facts(str(p)) if hasattr(voice_audio, "file_facts") else None
    if facts is not None:
        assert "elevenlabs" in str(facts).lower()


